// Package gen renders the static dependency-injector registration for a
// package's inject-tagged structs.
//
// # Layout contract
//
// The rendered file names the scanned structs and their field types exactly as
// the scanner read them, with no package qualifier, because NewGenerator is
// given only a package name and cannot build an import path. The output has to
// be written into the package it was scanned from:
//
//	infos, err := gen.NewScanner("internal/invoice").Scan()
//	if err != nil {
//		return err
//	}
//	err = gen.NewGenerator("invoice").Generate(infos, "internal/invoice/ioc_gen.go")
//
// Generating into a different package leaves every struct name unresolved and
// does not compile;
// TestGeneratedInjectorInAnotherPackageDoesNotCompile pins that limit.
//
// This package is compatibility-only: docs/supported-features.md retains it
// because v0.9.1 shipped it and the v0.9.1 API baseline pins it, while new code
// generation belongs to the `bear gen` CLI command.
package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"text/template"
)

// iocTemplate renders one injector registration per scanned struct.
//
// The framework import path is spelled out for the same reason ControllerTemplate
// and ServiceTemplate spell it out: this package generates code for a project that
// depends on the framework, and that path is fixed. The template previously
// referred to a {{.ModuleName}} field that Generate never supplied, so every call
// failed with "can't evaluate field ModuleName".
const iocTemplate = `// Code generated by bear gen. DO NOT EDIT.
package {{.PackageName}}

import (
	"github.com/duiniwukenaihe/gin-bear/pkg/bear"
)

func init() {
	// 注册静态注入函数到框架
	{{- range .Infos}}
		bear.RegisterRuntimeStaticInjector("{{.StructName}}", func(factory *bear.BeanFactory, obj interface{}) {
			target := obj.(*{{.StructName}})
			{{- range .Fields}}
			target.{{.FieldName}} = bear.Resolve[{{.TypeName}}](factory)
		{{- end}}
	})
	{{- end}}
}
`

type Generator struct {
	PackageName string
}

func NewGenerator(pkgName string) *Generator {
	return &Generator{PackageName: pkgName}
}

func (g *Generator) Generate(infos []InjectInfo, outputPath string) error {
	tmpl, err := template.New("ioc").Parse(iocTemplate)
	if err != nil {
		return err
	}

	data := struct {
		PackageName string
		Infos       []InjectInfo
	}{
		PackageName: g.PackageName,
		Infos:       infos,
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return err
	}

	// The template indents its body for readability, so the rendered source is
	// not gofmt clean on its own. Generated files are committed, so normalise them
	// the way the CLI generators do.
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format generated injector for %s: %w", g.PackageName, err)
	}

	// GenerateFromTemplate creates the output directory; Generate has to behave
	// the same way, or writing into a package directory that does not exist yet
	// fails for one method and succeeds for the other.
	if err := os.MkdirAll(filepath.Dir(outputPath), 0755); err != nil {
		return err
	}
	return os.WriteFile(outputPath, formatted, 0644)
}

func (g *Generator) GenerateFromTemplate(tmplStr string, data interface{}, outputPath string) error {
	tmpl, err := template.New("gen").Parse(tmplStr)
	if err != nil {
		return err
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return err
	}

	// 确保目录存在
	dir := filepath.Dir(outputPath)
	if err := os.MkdirAll(dir, 0755); err != nil {
		return err
	}

	return os.WriteFile(outputPath, buf.Bytes(), 0644)
}
